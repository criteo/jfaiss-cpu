import java.io.File;
import java.lang.invoke.MethodType;
import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Deque;
import java.util.List;

/**
 * Checks that every class, method and field listed in a file still exists, with the same JVM descriptor, in
 * a jar or a directory of classes.
 *
 * <p>The Java sources of this project are generated by SWIG from the Faiss headers, so a new Faiss or SWIG
 * version can rename a class, change a parameter from int to long or renumber an overload. Code that was
 * compiled against an older jar then fails at run time with NoSuchMethodError. The list holds the members
 * such code is known to use, in the form the JVM resolves them (see ci/list-api-refs.sh).
 *
 * <p>Run with a JDK 11 or later: {@code java ci/ApiCheck.java CLASSES_DIR_OR_JAR LIST_FILE}
 */
public class ApiCheck {

    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            System.err.println("usage: java ApiCheck.java CLASSES_DIR_OR_JAR LIST_FILE");
            System.exit(2);
        }
        final ClassLoader loader = new URLClassLoader(new URL[]{new File(args[0]).toURI().toURL()}, null);
        final List<String> missing = new ArrayList<>();
        int checked = 0;
        for (String line : Files.readAllLines(Paths.get(args[1]))) {
            final String entry = line.trim();
            if (entry.isEmpty() || entry.startsWith("#")) {
                continue;
            }
            checked++;
            final String problem = check(loader, entry);
            if (problem != null) {
                missing.add(entry + "\n        " + problem);
            }
        }
        for (String entry : missing) {
            System.out.println("MISSING " + entry);
        }
        System.out.println(args[0] + ": " + (checked - missing.size()) + " of " + checked + " required members found");
        if (checked == 0 || !missing.isEmpty()) {
            System.exit(1);
        }
    }

    /** An entry is {@code pkg/Class}, {@code pkg/Class.method:(args)ret} or {@code pkg/Class.field:type}. */
    private static String check(ClassLoader loader, String entry) {
        final int colon = entry.indexOf(':');
        final String owner;
        final String name;
        final String descriptor;
        if (colon < 0) {
            owner = entry;
            name = null;
            descriptor = null;
        } else {
            final int dot = entry.lastIndexOf('.', colon);
            owner = entry.substring(0, dot);
            name = entry.substring(dot + 1, colon);
            descriptor = entry.substring(colon + 1);
        }
        final Class<?> type;
        try {
            type = Class.forName(owner.replace('/', '.'), false, loader);
        } catch (ClassNotFoundException | LinkageError e) {
            return "class not found";
        }
        if (name == null) {
            return null;
        }
        // The JVM looks a member up in the class, then in its superclasses and interfaces.
        final List<String> sameName = new ArrayList<>();
        final Deque<Class<?>> todo = new ArrayDeque<>();
        todo.add(type);
        while (!todo.isEmpty()) {
            final Class<?> current = todo.remove();
            if (current.getSuperclass() != null) {
                todo.add(current.getSuperclass());
            }
            for (Class<?> implemented : current.getInterfaces()) {
                todo.add(implemented);
            }
            if (name.equals("<init>")) {
                if (current != type) {
                    continue;
                }
                for (Constructor<?> constructor : current.getDeclaredConstructors()) {
                    final String found = MethodType.methodType(void.class, constructor.getParameterTypes())
                            .toMethodDescriptorString();
                    if (matches(found, descriptor, constructor.getModifiers(), sameName)) {
                        return null;
                    }
                }
            } else if (descriptor.startsWith("(")) {
                for (Method method : current.getDeclaredMethods()) {
                    if (!method.getName().equals(name)) {
                        continue;
                    }
                    final String found = MethodType.methodType(method.getReturnType(), method.getParameterTypes())
                            .toMethodDescriptorString();
                    if (matches(found, descriptor, method.getModifiers(), sameName)) {
                        return null;
                    }
                }
            } else {
                for (Field field : current.getDeclaredFields()) {
                    if (!field.getName().equals(name)) {
                        continue;
                    }
                    // "(T)V" -> "T"
                    final String wrapped = MethodType.methodType(void.class, field.getType()).toMethodDescriptorString();
                    final String found = wrapped.substring(1, wrapped.length() - 2);
                    if (matches(found, descriptor, field.getModifiers(), sameName)) {
                        return null;
                    }
                }
            }
        }
        return sameName.isEmpty() ? "no member of that name" : "found instead: " + String.join(", ", sameName);
    }

    private static boolean matches(String found, String expected, int modifiers, List<String> sameName) {
        if (found.equals(expected) && !Modifier.isPrivate(modifiers)) {
            return true;
        }
        sameName.add((Modifier.isPrivate(modifiers) ? "private " : "") + found);
        return false;
    }
}
